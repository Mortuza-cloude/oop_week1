# A Suica card has a balance of 320 yen. 
# The train fare is 410 yen. Write an if-else statement that prints "Insufficient balance"
#  if the balance is less than the fare, otherwise print "You can board the train".


balance = 320
fare = 410
if balance < fare:
    print("Insufficient balance")   
else:
    print("You can board the train")